/** Vị trí Tasker minh họa: tiến dần về địa chỉ đơn theo thời gian */
export const mockTaskerLocation = (b: BookingResponse) => {
  const lat = b.latitude ?? 10.7743,
    lng = b.longitude ?? 106.7038;
  const t = (Date.now() / 1000) % 120; // chu kỳ 2 phút
  const k = 1 - t / 120;
  return {
    latitude: lat + 0.012 * k,
    longitude: lng - 0.014 * k,
    updatedAt: new Date().toISOString(),
    distanceKm: +(2.1 * k + 0.1).toFixed(1),
  };
};
